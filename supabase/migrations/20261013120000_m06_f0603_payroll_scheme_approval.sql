create table if not exists public.payroll_approval_events (
  id bigint generated by default as identity primary key,
  subject_type text not null check (subject_type in ('SCHEME', 'RUN')),
  subject_id uuid not null,
  action text not null,
  actor_id uuid references public.profiles(id) on delete set null,
  actor_name text,
  note text,
  details jsonb,
  created_at timestamptz not null default now()
);

create index if not exists payroll_approval_events_subject_idx
  on public.payroll_approval_events(subject_type, subject_id, created_at desc);

alter table public.payroll_approval_events enable row level security;
