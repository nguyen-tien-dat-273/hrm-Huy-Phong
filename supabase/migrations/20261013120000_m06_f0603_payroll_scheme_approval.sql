-- ---------------------------------------------------------------------------
-- 3. Đề xuất thay đổi cơ chế lương
-- ---------------------------------------------------------------------------
create table if not exists public.payroll_scheme_requests (
  id uuid primary key default gen_random_uuid(),
  code text not null unique
    default ('CCL-' || to_char(now(), 'YYMMDD') || '-' || upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 6))),
  target_type text not null check (target_type in ('USER', 'UNIT')),
  user_id uuid references public.profiles(id) on delete cascade,
  unit_id uuid references public.organization_units(id) on delete cascade,
  effective_from date not null,
  status text not null default 'DRAFT'
    check (status in ('DRAFT', 'SUBMITTED', 'APPROVED', 'REJECTED', 'CANCELLED')),
  /* USER: {profile: {...}, items: [...]}. UNIT: {items: [...]}. Xem
     `payroll_validate_scheme_payload`. Đây là TOÀN BỘ cơ chế từ tháng hiệu
     lực, không phải phần chênh lệch — duyệt xong là thay trọn. */
  payload jsonb not null,
  /* Căn cứ đề xuất: số quyết định, lý do điều chỉnh. */
  note text,
  created_by uuid references public.profiles(id) on delete set null default auth.uid(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  submitted_by uuid references public.profiles(id) on delete set null,
  submitted_at timestamptz,
  reviewed_by uuid references public.profiles(id) on delete set null,
  reviewed_at timestamptz,
  review_note text,
  /* SHA-256 của nội dung tại lúc ký duyệt — đối chiếu được về sau rằng thứ
     đang áp dụng đúng là thứ BGĐ đã ký. */
  approval_fingerprint text,
  applied_at timestamptz,
  constraint payroll_scheme_requests_first_day
    check (effective_from = date_trunc('month', effective_from)::date),
  constraint payroll_scheme_requests_target check (
    (target_type = 'USER' and user_id is not null and unit_id is null)
    or (target_type = 'UNIT' and unit_id is not null and user_id is null)
  ),
  constraint payroll_scheme_requests_reject_reason
    check (status <> 'REJECTED' or length(trim(coalesce(review_note, ''))) >= 3),
  constraint payroll_scheme_requests_payload_shape check (jsonb_typeof(payload) = 'object')
);

-- Mỗi đối tượng chỉ một đề xuất đang mở: hai bản nháp cho cùng một người thì
-- BGĐ duyệt cái nào, cái kia đi đâu — không trả lời được.
create unique index if not exists payroll_scheme_requests_one_open
  on public.payroll_scheme_requests(target_type, coalesce(user_id, unit_id))
  where status in ('DRAFT', 'SUBMITTED', 'REJECTED');

create index if not exists payroll_scheme_requests_status_idx
  on public.payroll_scheme_requests(status, submitted_at desc);

drop trigger if exists payroll_scheme_requests_touch on public.payroll_scheme_requests;
create trigger payroll_scheme_requests_touch
before update on public.payroll_scheme_requests
for each row execute function public.touch_payroll_updated_at();

alter table public.payroll_scheme_requests enable row level security;
drop policy if exists payroll_scheme_requests_read on public.payroll_scheme_requests;
create policy payroll_scheme_requests_read on public.payroll_scheme_requests
for select to authenticated using (
  public.can_function('admin.payroll_schemes')
  or public.can_function('admin.payroll_approve')
  or public.can_function('admin.payroll')
);
revoke insert, update, delete on public.payroll_scheme_requests from authenticated, anon;
grant select on public.payroll_scheme_requests to authenticated;

-- Kiểm tra nội dung đề xuất. `p_full = false` khi lưu nháp: chỉ chặn số sai
-- định dạng / số âm (luồng ngoại lệ 1). `p_full = true` khi trình và khi duyệt:
-- thêm kiểm lương tối thiểu vùng và quy tắc phiên bản.
create or replace function public.payroll_validate_scheme_payload(
  p_target_type text,
  p_target_id uuid,
  p_effective_from date,
  p_payload jsonb,
  p_full boolean
)
returns void
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v_item jsonb;
  v_profile jsonb := p_payload -> 'profile';
  v_component public.payroll_components%rowtype;
  v_seen uuid[] := '{}';
  v_base_count integer := 0;
  v_base_amount numeric;
  v_version public.payroll_param_versions%rowtype;
  v_last date := public.payroll_last_closed_month();
  v_num text;
begin
  if jsonb_typeof(p_payload -> 'items') is distinct from 'array' then
    raise exception 'Đề xuất thiếu danh sách khoản lương.' using errcode = '22023';
  end if;
  if p_effective_from is null or p_effective_from <> date_trunc('month', p_effective_from)::date then
    raise exception 'Tháng áp dụng phải là ngày đầu tháng.' using errcode = '22023';
  end if;
  if v_last is not null and p_effective_from <= v_last then
    raise exception 'Kỳ lương tháng % đã chốt — cơ chế mới phải áp dụng từ tháng % trở đi.',
      to_char(v_last, 'MM/YYYY'), to_char(v_last + interval '1 month', 'MM/YYYY') using errcode = '23514';
  end if;

  for v_item in select value from jsonb_array_elements(p_payload -> 'items')
  loop
    if jsonb_typeof(v_item -> 'component_id') is distinct from 'string' then
      raise exception 'Có khoản chưa chọn trong danh mục.' using errcode = '22023';
    end if;
    select * into v_component from public.payroll_components
    where id = (v_item ->> 'component_id')::uuid;
    if v_component.id is null then
      raise exception 'Khoản lương không còn trong danh mục.' using errcode = '23503';
    end if;
    if v_component.calc_source = 'ENGINE' then
      raise exception 'Khoản "%" do hệ thống tự tính, không khai trong cơ chế.', v_component.name using errcode = '23514';
    end if;
    if v_component.id = any(v_seen) then
      raise exception 'Khoản "%" bị khai hai lần.', v_component.name using errcode = '23505';
    end if;
    v_seen := array_append(v_seen, v_component.id);

    if v_item ? 'amount' and jsonb_typeof(v_item -> 'amount') <> 'null' then
      if jsonb_typeof(v_item -> 'amount') is distinct from 'number' then
        raise exception 'Mức của khoản "%" phải là số.', v_component.name using errcode = '22023';
      end if;
      if (v_item ->> 'amount')::numeric < 0 then
        raise exception 'Mức của khoản "%" không được âm.', v_component.name using errcode = '23514';
      end if;
    end if;
    if v_item ? 'formula' and jsonb_typeof(v_item -> 'formula') not in ('null', 'string') then
      raise exception 'Công thức khoản "%" không hợp lệ.', v_component.name using errcode = '22023';
    end if;
    if length(coalesce(v_item ->> 'formula', '')) > 2000 then
      raise exception 'Công thức khoản "%" quá dài.', v_component.name using errcode = '22023';
    end if;

    if coalesce((v_item ->> 'is_base')::boolean, v_component.is_base) then
      v_base_count := v_base_count + 1;
      if jsonb_typeof(v_item -> 'amount') = 'number' then
        v_base_amount := (v_item ->> 'amount')::numeric;
      end if;
    end if;
  end loop;

  if v_base_count > 1 then
    raise exception 'Mỗi cơ chế chỉ được MỘT khoản lương gốc.' using errcode = '23514';
  end if;

  if p_target_type = 'USER' then
    if jsonb_typeof(v_profile) is distinct from 'object' then
      raise exception 'Đề xuất thiếu thông tin người phụ thuộc / bảo hiểm / thuế.' using errcode = '22023';
    end if;
    v_num := v_profile ->> 'dependents';
    if jsonb_typeof(v_profile -> 'dependents') is distinct from 'number'
      or v_num::numeric < 0 or v_num::numeric > 30 or v_num::numeric <> trunc(v_num::numeric) then
      raise exception 'Số người phụ thuộc phải là số nguyên từ 0.' using errcode = '22023';
    end if;
    if jsonb_typeof(v_profile -> 'insurance_base') = 'number' and (v_profile ->> 'insurance_base')::numeric < 0 then
      raise exception 'Mức lương đóng bảo hiểm không được âm.' using errcode = '23514';
    end if;
    if coalesce(v_profile ->> 'tax_mode', 'PROGRESSIVE') not in ('PROGRESSIVE', 'FLAT', 'NONE') then
      raise exception 'Cách tính thuế không hợp lệ.' using errcode = '22023';
    end if;
    if jsonb_typeof(v_profile -> 'flat_tax_rate') = 'number'
      and ((v_profile ->> 'flat_tax_rate')::numeric < 0 or (v_profile ->> 'flat_tax_rate')::numeric > 100) then
      raise exception 'Thuế suất khấu trừ thẳng phải từ 0 đến 100%%.' using errcode = '23514';
    end if;
    if jsonb_typeof(v_profile -> 'standard_days_override') = 'number'
      and ((v_profile ->> 'standard_days_override')::numeric <= 0 or (v_profile ->> 'standard_days_override')::numeric > 31) then
      raise exception 'Ngày công chuẩn riêng phải trong khoảng 0–31.' using errcode = '23514';
    end if;
    if jsonb_typeof(v_profile -> 'template_id') = 'string' and not exists (
      select 1 from public.payroll_templates t
      where t.id = (v_profile ->> 'template_id')::uuid and t.is_active
    ) then
      raise exception 'Mẫu bảng lương đã chọn không còn dùng.' using errcode = '23503';
    end if;
  end if;

  if not p_full then
    return;
  end if;

  -- BR-PAY-013: lương cơ bản >= lương tối thiểu vùng tại tháng áp dụng.
  select * into v_version from public.payroll_param_version_for(p_effective_from);
  if v_version.id is null then
    raise exception 'Chưa có bộ tham số lương hiệu lực cho tháng % — khai ở Tham số lương trước.',
      to_char(p_effective_from, 'MM/YYYY') using errcode = '23514';
  end if;
  if v_base_amount is not null and v_base_amount < v_version.regional_minimum_wage then
    raise exception 'Mức lương cơ bản % thấp hơn lương tối thiểu vùng % (vùng %, BR-PAY-013).',
      replace(to_char(v_base_amount, 'FM999,999,999,999'), ',', '.'), replace(to_char(v_version.regional_minimum_wage, 'FM999,999,999,999'), ',', '.'),
      v_version.region_code
      using errcode = '23514';
  end if;

  -- Không chen một phiên bản vào TRƯỚC phiên bản đã có hiệu lực sau đó.
  if p_target_type = 'USER' and (
    exists (select 1 from public.employee_pay_profiles where user_id = p_target_id and effective_from > p_effective_from)
    or exists (select 1 from public.employee_pay_items where user_id = p_target_id and effective_from > p_effective_from)
  ) then
    raise exception 'Người này đã có cơ chế hiệu lực sau tháng % — đề xuất phải áp dụng từ sau mốc đó.',
      to_char(p_effective_from, 'MM/YYYY') using errcode = '23514';
  end if;
  if p_target_type = 'UNIT' and exists (
    select 1 from public.unit_pay_items where unit_id = p_target_id and effective_from > p_effective_from
  ) then
    raise exception 'Đơn vị này đã có khoản chung hiệu lực sau tháng % — đề xuất phải áp dụng từ sau mốc đó.',
      to_char(p_effective_from, 'MM/YYYY') using errcode = '23514';
  end if;
end;
$$;

revoke all on function public.payroll_validate_scheme_payload(text, uuid, date, jsonb, boolean) from public, anon, authenticated;

-- Lưu nháp hoặc lưu & trình duyệt.
create or replace function public.save_payroll_scheme_request(
  p_request_id uuid,
  p_target_type text,
  p_user_id uuid,
  p_unit_id uuid,
  p_effective_from date,
  p_payload jsonb,
  p_note text,
  p_submit boolean
)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_request public.payroll_scheme_requests%rowtype;
  v_target uuid := coalesce(p_user_id, p_unit_id);
  v_id uuid;
begin
  if auth.uid() is null or not public.can_function('admin.payroll_schemes') then
    raise exception 'Bạn không có quyền thiết lập cơ chế lương.' using errcode = '42501';
  end if;
  if p_target_type not in ('USER', 'UNIT') then
    raise exception 'Đối tượng đề xuất không hợp lệ.' using errcode = '22023';
  end if;

  perform public.payroll_validate_scheme_payload(p_target_type, v_target, p_effective_from, p_payload, coalesce(p_submit, false));

  if p_request_id is null then
    if exists (
      select 1 from public.payroll_scheme_requests r
      where r.target_type = p_target_type and coalesce(r.user_id, r.unit_id) = v_target
        and r.status in ('DRAFT', 'SUBMITTED', 'REJECTED')
    ) then
      raise exception 'Đối tượng này đang có một đề xuất chưa xử lý xong — mở đề xuất đó để sửa.' using errcode = '23505';
    end if;
    insert into public.payroll_scheme_requests (target_type, user_id, unit_id, effective_from, payload, note)
    values (
      p_target_type,
      case when p_target_type = 'USER' then p_user_id end,
      case when p_target_type = 'UNIT' then p_unit_id end,
      p_effective_from, p_payload, nullif(trim(coalesce(p_note, '')), '')
    )
    returning * into v_request;
  else
    select * into v_request from public.payroll_scheme_requests where id = p_request_id for update;
    if v_request.id is null then
      raise exception 'Không tìm thấy đề xuất.' using errcode = 'P0002';
    end if;
    if v_request.status not in ('DRAFT', 'REJECTED') then
      raise exception 'Đề xuất đang chờ duyệt hoặc đã xử lý — không sửa được.' using errcode = '23514';
    end if;
    if v_request.target_type <> p_target_type or coalesce(v_request.user_id, v_request.unit_id) <> v_target then
      raise exception 'Không đổi được đối tượng của đề xuất.' using errcode = '22023';
    end if;
    update public.payroll_scheme_requests
    set effective_from = p_effective_from,
        payload = p_payload,
        note = nullif(trim(coalesce(p_note, '')), ''),
        status = 'DRAFT'
    where id = p_request_id
    returning * into v_request;
  end if;

  v_id := v_request.id;
  perform public.add_payroll_approval_event('SCHEME', v_id, 'SAVED', null,
    jsonb_build_object('effective_from', p_effective_from));

  if coalesce(p_submit, false) then
    update public.payroll_scheme_requests
    set status = 'SUBMITTED', submitted_by = auth.uid(), submitted_at = now(),
        reviewed_by = null, reviewed_at = null, review_note = null
    where id = v_id;
    perform public.add_payroll_approval_event('SCHEME', v_id, 'SUBMITTED', p_note, null);
    perform public.write_payroll_audit(
      'salary.scheme_submit', 'payroll_scheme_request', v_id::text,
      format('Trình duyệt cơ chế lương %s từ %s', v_request.code, to_char(p_effective_from, 'MM/YYYY')),
      jsonb_build_object('payload', p_payload), p_user_id
    );
  end if;

  return v_id;
end;
$$;

revoke all on function public.save_payroll_scheme_request(uuid, text, uuid, uuid, date, jsonb, text, boolean) from public;
grant execute on function public.save_payroll_scheme_request(uuid, text, uuid, uuid, date, jsonb, text, boolean) to authenticated;

create or replace function public.cancel_payroll_scheme_request(p_request_id uuid, p_reason text default null)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_request public.payroll_scheme_requests%rowtype;
begin
  if auth.uid() is null or not public.can_function('admin.payroll_schemes') then
    raise exception 'Bạn không có quyền thiết lập cơ chế lương.' using errcode = '42501';
  end if;
  select * into v_request from public.payroll_scheme_requests where id = p_request_id for update;
  if v_request.id is null or v_request.status not in ('DRAFT', 'SUBMITTED', 'REJECTED') then
    raise exception 'Đề xuất không còn huỷ được.' using errcode = '23514';
  end if;
  update public.payroll_scheme_requests set status = 'CANCELLED' where id = p_request_id;
  perform public.add_payroll_approval_event('SCHEME', p_request_id, 'CANCELLED', p_reason, null);
end;
$$;

revoke all on function public.cancel_payroll_scheme_request(uuid, text) from public;
grant execute on function public.cancel_payroll_scheme_request(uuid, text) to authenticated;

-- Ghi đề xuất đã duyệt vào bảng cơ chế, theo phiên bản.
create or replace function public.apply_payroll_scheme_request(p_request public.payroll_scheme_requests)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_eff date := p_request.effective_from;
  v_close date := (p_request.effective_from - interval '1 day')::date;
  v_profile jsonb := p_request.payload -> 'profile';
  v_version public.payroll_param_versions%rowtype;
begin
  if p_request.target_type = 'USER' then
    select * into v_version from public.payroll_param_version_for(v_eff);

    insert into public.employee_pay_profiles (
      user_id, effective_from, pay_basis, base_amount, insurance_base, insurance_enabled,
      dependents, tax_mode, flat_tax_rate, standard_days_override, template_id, note, created_by
    ) values (
      p_request.user_id, v_eff, 'MONTHLY', 0,
      case when jsonb_typeof(v_profile -> 'insurance_base') = 'number' then (v_profile ->> 'insurance_base')::numeric end,
      coalesce((v_profile ->> 'insurance_enabled')::boolean, true),
      coalesce((v_profile ->> 'dependents')::integer, 0),
      coalesce(v_profile ->> 'tax_mode', 'PROGRESSIVE'),
      coalesce(
        case when jsonb_typeof(v_profile -> 'flat_tax_rate') = 'number' then (v_profile ->> 'flat_tax_rate')::numeric end,
        v_version.flat_tax_rate, 10
      ),
      case when jsonb_typeof(v_profile -> 'standard_days_override') = 'number'
        then (v_profile ->> 'standard_days_override')::numeric end,
      case when jsonb_typeof(v_profile -> 'template_id') = 'string' then (v_profile ->> 'template_id')::uuid end,
      coalesce(p_request.note, 'Áp dụng theo đề xuất ' || p_request.code),
      p_request.submitted_by
    )
    on conflict (user_id, effective_from) do update set
      pay_basis = excluded.pay_basis,
      base_amount = excluded.base_amount,
      insurance_base = excluded.insurance_base,
      insurance_enabled = excluded.insurance_enabled,
      dependents = excluded.dependents,
      tax_mode = excluded.tax_mode,
      flat_tax_rate = excluded.flat_tax_rate,
      standard_days_override = excluded.standard_days_override,
      template_id = excluded.template_id,
      note = excluded.note;

    update public.employee_pay_items
    set effective_to = v_close
    where user_id = p_request.user_id
      and effective_from < v_eff
      and (effective_to is null or effective_to >= v_eff);
    delete from public.employee_pay_items
    where user_id = p_request.user_id and effective_from >= v_eff;

    insert into public.employee_pay_items (
      user_id, component_id, amount, formula, taxable, insurable, is_base, effective_from, note, created_by
    )
    select
      p_request.user_id,
      (i ->> 'component_id')::uuid,
      case when jsonb_typeof(i -> 'amount') = 'number' then (i ->> 'amount')::numeric end,
      nullif(trim(coalesce(i ->> 'formula', '')), ''),
      case when jsonb_typeof(i -> 'taxable') = 'boolean' then (i ->> 'taxable')::boolean end,
      case when jsonb_typeof(i -> 'insurable') = 'boolean' then (i ->> 'insurable')::boolean end,
      case when jsonb_typeof(i -> 'is_base') = 'boolean' then (i ->> 'is_base')::boolean end,
      v_eff,
      nullif(trim(coalesce(i ->> 'note', '')), ''),
      p_request.submitted_by
    from jsonb_array_elements(p_request.payload -> 'items') i;
  else
    update public.unit_pay_items
    set effective_to = v_close
    where unit_id = p_request.unit_id
      and effective_from < v_eff
      and (effective_to is null or effective_to >= v_eff);
    delete from public.unit_pay_items
    where unit_id = p_request.unit_id and effective_from >= v_eff;

    insert into public.unit_pay_items (unit_id, component_id, amount, formula, effective_from, note, created_by)
    select
      p_request.unit_id,
      (i ->> 'component_id')::uuid,
      case when jsonb_typeof(i -> 'amount') = 'number' then (i ->> 'amount')::numeric end,
      nullif(trim(coalesce(i ->> 'formula', '')), ''),
      v_eff,
      nullif(trim(coalesce(i ->> 'note', '')), ''),
      p_request.submitted_by
    from jsonb_array_elements(p_request.payload -> 'items') i;
  end if;
end;
$$;

revoke all on function public.apply_payroll_scheme_request(public.payroll_scheme_requests) from public, anon, authenticated;

-- BGĐ ký duyệt / từ chối. Ký = phải vừa xác thực lại (mật khẩu hoặc mã TOTP)
-- trong 5 phút gần nhất.
create or replace function public.review_payroll_scheme_request(
  p_request_id uuid,
  p_decision text,
  p_note text default null
)
returns void
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_request public.payroll_scheme_requests%rowtype;
  v_fingerprint text;
begin
  if auth.uid() is null or not public.can_function('admin.payroll_approve') then
    raise exception 'Chỉ Ban Giám đốc (chức năng Phê duyệt lương) được duyệt cơ chế lương.' using errcode = '42501';
  end if;
  if p_decision not in ('APPROVED', 'REJECTED') then
    raise exception 'Quyết định không hợp lệ.' using errcode = '22023';
  end if;
  if not public.payroll_recent_auth(5, array['password', 'totp']) then
    raise exception 'Cần nhập lại mật khẩu để ký duyệt.' using errcode = '28000';
  end if;

  select * into v_request from public.payroll_scheme_requests where id = p_request_id for update;
  if v_request.id is null then
    raise exception 'Không tìm thấy đề xuất.' using errcode = 'P0002';
  end if;
  if v_request.status <> 'SUBMITTED' then
    raise exception 'Đề xuất không ở trạng thái chờ duyệt.' using errcode = '23514';
  end if;
  -- Tách người trình và người duyệt. Admin/CEO là ngoại lệ có chủ đích: công
  -- ty nhỏ có thể chỉ một người vừa khai vừa duyệt, và vai trò đó vốn toàn quyền.
  if v_request.submitted_by = auth.uid() and not public.is_admin() then
    raise exception 'Người trình không tự duyệt đề xuất của mình.' using errcode = '42501';
  end if;

  if p_decision = 'REJECTED' then
    if length(trim(coalesce(p_note, ''))) < 3 then
      raise exception 'Từ chối phải ghi rõ lý do.' using errcode = '23514';
    end if;
    update public.payroll_scheme_requests
    set status = 'REJECTED', reviewed_by = auth.uid(), reviewed_at = now(), review_note = trim(p_note)
    where id = p_request_id;
    perform public.add_payroll_approval_event('SCHEME', p_request_id, 'REJECTED', p_note, null);
    perform public.write_payroll_audit(
      'salary.scheme_reject', 'payroll_scheme_request', p_request_id::text,
      format('Từ chối cơ chế lương %s: %s', v_request.code, trim(p_note)), null, v_request.user_id
    );
    return;
  end if;

  perform public.payroll_validate_scheme_payload(
    v_request.target_type, coalesce(v_request.user_id, v_request.unit_id),
    v_request.effective_from, v_request.payload, true
  );

  v_fingerprint := encode(digest(
    v_request.target_type || '|' || coalesce(v_request.user_id, v_request.unit_id)::text || '|'
      || v_request.effective_from::text || '|' || v_request.payload::text,
    'sha256'), 'hex');

  perform public.apply_payroll_scheme_request(v_request);

  update public.payroll_scheme_requests
  set status = 'APPROVED', reviewed_by = auth.uid(), reviewed_at = now(),
      review_note = nullif(trim(coalesce(p_note, '')), ''),
      approval_fingerprint = v_fingerprint, applied_at = now()
  where id = p_request_id;

  perform public.add_payroll_approval_event('SCHEME', p_request_id, 'APPROVED', p_note,
    jsonb_build_object('fingerprint', v_fingerprint));
  perform public.write_payroll_audit(
    'salary.scheme_approve', 'payroll_scheme_request', p_request_id::text,
    format('Ký duyệt cơ chế lương %s, hiệu lực từ %s', v_request.code, to_char(v_request.effective_from, 'MM/YYYY')),
    jsonb_build_object('payload', v_request.payload, 'fingerprint', v_fingerprint), v_request.user_id
  );
end;
$$;

revoke all on function public.review_payroll_scheme_request(uuid, text, text) from public;
grant execute on function public.review_payroll_scheme_request(uuid, text, text) to authenticated;

-- ---------------------------------------------------------------------------
-- 4. Ba bảng cơ chế: không còn ghi thẳng từ client
-- ---------------------------------------------------------------------------
-- Đường ghi duy nhất là `review_payroll_scheme_request` (đề xuất đã được BGĐ
-- ký). Để mở ghi thẳng thì bản nháp vẫn lách qua được duyệt, đúng thứ
-- BR-PAY-012 cấm.
--
-- Quyền ĐỌC mở thêm cho người khai cơ chế và người duyệt (trước chỉ có
-- `admin.payroll`), vì họ cần thấy cơ chế hiện hành để so với đề xuất.
drop policy if exists employee_pay_profiles_manage on public.employee_pay_profiles;
drop policy if exists employee_pay_items_manage on public.employee_pay_items;
drop policy if exists unit_pay_items_manage on public.unit_pay_items;

drop policy if exists employee_pay_profiles_read on public.employee_pay_profiles;
create policy employee_pay_profiles_read on public.employee_pay_profiles
for select to authenticated using (
  public.can_function('admin.payroll') or public.can_function('admin.payroll_schemes')
  or public.can_function('admin.payroll_approve')
  or (user_id = auth.uid() and public.payroll_recent_auth(15))
);

drop policy if exists employee_pay_items_read on public.employee_pay_items;
create policy employee_pay_items_read on public.employee_pay_items
for select to authenticated using (
  public.can_function('admin.payroll') or public.can_function('admin.payroll_schemes')
  or public.can_function('admin.payroll_approve')
  or (user_id = auth.uid() and public.payroll_recent_auth(15))
);

revoke insert, update, delete on public.employee_pay_profiles, public.employee_pay_items, public.unit_pay_items
  from authenticated, anon;
grant select on public.employee_pay_profiles, public.employee_pay_items, public.unit_pay_items to authenticated;

-- Audit cho chính ba bảng: phòng khi có người sửa bằng SQL trực tiếp, vết vẫn
-- nằm đó.
create or replace function public.audit_payroll_scheme_rows()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_row jsonb := to_jsonb(coalesce(new, old));
begin
  perform public.write_payroll_audit(
    'salary.scheme_row_' || lower(tg_op),
    tg_table_name,
    v_row ->> 'id',
    format('%s %s', case tg_op when 'INSERT' then 'Ghi' when 'UPDATE' then 'Cập nhật' else 'Xoá' end, tg_table_name),
    case tg_op
      when 'UPDATE' then jsonb_build_object('changes', public.payroll_row_diff(to_jsonb(old), to_jsonb(new)))
      else jsonb_build_object('row', v_row)
    end,
    case when v_row ? 'user_id' then (v_row ->> 'user_id')::uuid end
  );
  return coalesce(new, old);
end;
$$;

do $do$
declare
  t text;
begin
  foreach t in array array['employee_pay_profiles', 'employee_pay_items', 'unit_pay_items'] loop
    execute format('drop trigger if exists %I_audit on public.%I', t, t);
    execute format(
      'create trigger %I_audit after insert or update or delete on public.%I
       for each row execute function public.audit_payroll_scheme_rows()', t, t);
  end loop;
end;
$do$;
