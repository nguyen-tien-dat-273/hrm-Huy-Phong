revoke all on function public.add_payroll_approval_event(text, uuid, text, text, jsonb) from public, anon, authenticated;

-- ---------------------------------------------------------------------------
-- 2. Xác thực lại gần đây — "chữ ký" khi duyệt và khoá
-- ---------------------------------------------------------------------------
-- JWT của Supabase mang `amr`: danh sách cách người dùng đã xác thực trong
-- phiên kèm thời điểm. Đăng nhập lại bằng mật khẩu (hoặc nhập mã TOTP) sinh
-- một mốc mới. Hàm này hỏi: trong N phút qua người này có xác thực lại không.
--
-- Đây là thứ biến một cú bấm "Duyệt" thành một lần KÝ: phiên bị bỏ quên trên
-- máy người khác không duyệt được lương, vì người ngồi vào máy không biết mật
-- khẩu. Kiểm ở database, giao diện không lách được.
create or replace function public.payroll_recent_auth(p_minutes integer, p_methods text[] default null)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from jsonb_array_elements(
      case when jsonb_typeof(auth.jwt() -> 'amr') = 'array' then auth.jwt() -> 'amr' else '[]'::jsonb end
    ) a
    where jsonb_typeof(a -> 'timestamp') = 'number'
      and (a ->> 'timestamp')::numeric >= extract(epoch from now()) - p_minutes * 60
      and (p_methods is null or (a ->> 'method') = any(p_methods))
  );
$$;

revoke all on function public.payroll_recent_auth(integer, text[]) from public;
grant execute on function public.payroll_recent_auth(integer, text[]) to authenticated;

-- Người duyệt lương (BGĐ): ai có chức năng `admin.payroll_approve` (Admin/CEO
-- ngầm định có). Dùng để gửi thông báo trình ký.
create or replace function public.get_payroll_approver_ids()
returns table (user_id uuid)
language plpgsql
stable
security definer
set search_path = public
as $$
begin
  if auth.uid() is null or not public.can_payroll() then
    raise exception 'Bạn không có quyền xem danh sách người duyệt lương.' using errcode = '42501';
  end if;
