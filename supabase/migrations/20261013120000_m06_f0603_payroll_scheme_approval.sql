-- ============================================================================
-- M06 · F06.03 — Cơ chế lương theo sơ đồ tổ chức, có BGĐ ký duyệt.
-- ----------------------------------------------------------------------------
-- Đặc tả F06.03 và BR-PAY-012: "Mọi thay đổi về thang bảng lương và mức phụ
-- cấp bắt buộc phải có quyết định phê duyệt điện tử của Ban Giám đốc mới có
-- hiệu lực áp dụng". Luồng ngoại lệ: "Chưa được BGĐ phê duyệt -> Bản nháp,
-- engine KHÔNG được dùng số liệu này để chạy bảng lương chính thức."
--
-- Hiện trạng: màn Cơ chế lương ghi THẲNG vào `employee_pay_profiles` /
-- `employee_pay_items` / `unit_pay_items` — lưu là có hiệu lực ngay, không ai
-- duyệt. Và lưu đè `effective_from` của dòng cũ, nên khoản đang chạy từ tháng
-- 1 bị dời sang tháng 10 là các tháng 1–9 (chưa chốt) mất khoản đó.
--
-- Mô hình mới:
--   payroll_scheme_requests   ĐỀ XUẤT thay đổi: toàn bộ cơ chế mới của một
--                             người (hoặc khoản chung của một phòng) kèm tháng
--                             bắt đầu hiệu lực. DRAFT -> SUBMITTED -> APPROVED
--                             | REJECTED. Engine không đọc bảng này.
--   review_payroll_scheme_request   BGĐ ký duyệt (xác thực lại ngay lúc ký) —
--                             lúc đó mới GHI vào ba bảng cơ chế, theo phiên
--                             bản: đóng dòng cũ ở cuối tháng trước, mở dòng
--                             mới từ tháng hiệu lực.
--   Ba bảng cơ chế không còn ghi thẳng được từ client.
--
-- Kiểm tra lúc trình và lúc duyệt (BR-PAY-013): mức lương cơ bản không thấp
-- hơn lương tối thiểu vùng của bộ tham số có hiệu lực tại tháng áp dụng.
--
-- Chạy lại được nhiều lần.
-- ============================================================================

