grant select on public.payroll_approval_events to authenticated;

create or replace function public.add_payroll_approval_event(
  p_subject_type text, p_subject_id uuid, p_action text, p_note text default null, p_details jsonb default null
)
returns void
language plpgsql
security definer
set search_path = public
as $$
